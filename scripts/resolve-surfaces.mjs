/**
 * Works out which image each surface should use, and writes the answer out as
 * a plain TypeScript module.
 *
 * This used to be an existsSync() call inside the component. That is fine on a
 * Node server but not on Cloudflare Workers, where there is no filesystem to
 * read — the check would either throw or silently report every photo missing,
 * dropping the whole site back to the generated textures.
 *
 * Doing it here keeps the behaviour that matters: drop a correctly named file
 * into public/photos, build, and it is used; remove it and the texture comes
 * back. The lookup just happens once at build time instead of at import time,
 * and the runtime receives a flat object it can read anywhere.
 *
 *   node scripts/resolve-surfaces.mjs
 *
 * Runs automatically as part of `npm run build`.
 */

import { existsSync, writeFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src", "components", "ui", "surfaces.generated.ts");

/** photo: preferred real photograph. texture: generated stand-in. */
const SOURCES = {
  hero: { photo: "/photos/hero.jpg", texture: "/textures/asphalt-hero.jpg" },
  oxidized: { photo: "/photos/dried-asphalt.jpg", texture: "/textures/asphalt-oxidized.jpg" },
  crack: { photo: "/photos/crack-sealing.jpg", texture: "/textures/asphalt-crack.jpg" },
  pothole: { photo: "/photos/pothole.jpg", texture: "/textures/asphalt-pothole.jpg" },
  lot: { photo: "/photos/line-striping.jpg", texture: "/textures/asphalt-lot.jpg" },
  driveway: { photo: "/photos/sealcoating.jpg", texture: "/textures/asphalt-driveway.jpg" },
};

const entries = Object.entries(SOURCES).map(([name, { photo, texture }]) => {
  const usingPhoto = existsSync(join(ROOT, "public", photo));
  return [name, usingPhoto ? photo : texture, usingPhoto];
});

const body = `// GENERATED by scripts/resolve-surfaces.mjs — do not edit by hand.
//
// Regenerated on every build. To change which image a surface uses, add or
// remove the file in public/photos and rebuild; see public/photos/README.md.

export const SURFACE_SRC = {
${entries.map(([name, src, usingPhoto]) => `  ${name}: "${src}",${usingPhoto ? "" : " // photo missing — generated texture"}`).join("\n")}
} as const;

export type SurfaceName = keyof typeof SURFACE_SRC;
`;

// Only write when something changed, so a no-op build does not dirty the tree.
const previous = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
if (previous !== body) {
  writeFileSync(OUT, body);
  console.log(`surfaces: wrote ${OUT}`);
} else {
  console.log("surfaces: unchanged");
}

const missing = entries.filter(([, , usingPhoto]) => !usingPhoto).map(([name]) => name);
if (missing.length > 0) {
  console.log(`surfaces: using generated textures for ${missing.join(", ")}`);
}
